-- Review-only migration for the Milestone Certificate Institute application.
-- This creates only the app_role type, profiles, user_roles, and the role-check
-- RPCs those tables require. It is NOT the complete application database schema:
-- the app also expects other tables, enums, triggers, and RPCs.
-- Apply to a disposable/staging project first and inspect existing functions/types;
-- this draft replaces has_role/has_role_text with identity-bound implementations.
-- Back up production, then use the authorized Supabase migration path.

BEGIN;

-- Match the enum values declared in src/integrations/supabase/types.ts.
-- If an existing enum is missing any required label, stop for explicit review
-- rather than silently changing a production type.
DO $migration$
DECLARE
  missing_labels text[];
BEGIN
  IF to_regtype('public.app_role') IS NULL THEN
    EXECUTE $ddl$
      CREATE TYPE public.app_role AS ENUM (
        'admin',
        'staff',
        'agent',
        'service_provider',
        'management'
      )
    $ddl$;
  ELSE
    SELECT array_agg(required.label ORDER BY required.ordinal)
      INTO missing_labels
    FROM unnest(
      ARRAY['admin', 'staff', 'agent', 'service_provider', 'management']::text[]
    ) WITH ORDINALITY AS required(label, ordinal)
    WHERE NOT EXISTS (
      SELECT 1
      FROM pg_catalog.pg_enum AS existing
      WHERE existing.enumtypid = to_regtype('public.app_role')::oid
        AND existing.enumlabel = required.label
    );

    IF missing_labels IS NOT NULL THEN
      RAISE EXCEPTION
        'public.app_role is missing required labels: %; review the existing enum before applying this migration',
        missing_labels;
    END IF;
  END IF;
END
$migration$;

-- Profile fields match the generated Database type. IDs are Auth user IDs;
-- deleting an Auth user removes its profile.
CREATE TABLE public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  email text,
  full_name text
);

-- A user may hold more than one distinct role, but duplicate role assignments
-- are prevented. IDs are generated by PostgreSQL as in the generated type.
CREATE TABLE public.user_roles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  role public.app_role NOT NULL,
  CONSTRAINT user_roles_user_id_role_key UNIQUE (user_id, role)
);

CREATE INDEX user_roles_role_idx ON public.user_roles (role);

COMMENT ON TABLE public.profiles IS
  'Application profile metadata keyed by the corresponding auth.users ID.';
COMMENT ON TABLE public.user_roles IS
  'Application authorization roles; role changes must be made through trusted server-side administration.';

-- These functions are called by authenticated application code and by the RLS
-- policies below. Restrict checks to the caller's own JWT identity so an
-- authenticated user cannot probe another user's role by supplying an ID.
-- SECURITY DEFINER lets the function read user_roles despite its RLS policies;
-- the empty search_path and fully-qualified object names avoid search-path attacks.
CREATE OR REPLACE FUNCTION public.has_role(
  _user_id uuid,
  _role public.app_role
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT COALESCE(auth.uid() = _user_id, false)
    AND EXISTS (
      SELECT 1
      FROM public.user_roles AS role_row
      WHERE role_row.user_id = _user_id
        AND role_row.role = _role
    );
$function$;

CREATE OR REPLACE FUNCTION public.has_role_text(
  _user_id uuid,
  _role text
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT COALESCE(auth.uid() = _user_id, false)
    AND EXISTS (
      SELECT 1
      FROM public.user_roles AS role_row
      WHERE role_row.user_id = _user_id
        AND role_row.role::text = _role
    );
$function$;

REVOKE ALL ON FUNCTION public.has_role(uuid, public.app_role) FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.has_role_text(uuid, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.has_role(uuid, public.app_role) TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.has_role_text(uuid, text) TO authenticated, service_role;

-- Authenticated users may read their own rows. Admins and staff may read all
-- profile/role rows because the current Settings > Users view exposes that list
-- to both roles; this intentionally exposes profile emails and role labels to
-- staff. Revisit this policy if the UI is narrowed to admins only. No client-side
-- INSERT/UPDATE/DELETE policy is created; trusted server-side writes use service_role.
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_roles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS profiles_select_own ON public.profiles;
CREATE POLICY profiles_select_own
  ON public.profiles
  FOR SELECT
  TO authenticated
  USING (id = (SELECT auth.uid()));

DROP POLICY IF EXISTS profiles_select_admin_staff ON public.profiles;
CREATE POLICY profiles_select_admin_staff
  ON public.profiles
  FOR SELECT
  TO authenticated
  USING (
    public.has_role((SELECT auth.uid()), 'admin'::public.app_role)
    OR public.has_role((SELECT auth.uid()), 'staff'::public.app_role)
  );

DROP POLICY IF EXISTS user_roles_select_own ON public.user_roles;
CREATE POLICY user_roles_select_own
  ON public.user_roles
  FOR SELECT
  TO authenticated
  USING (user_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS user_roles_select_admin_staff ON public.user_roles;
CREATE POLICY user_roles_select_admin_staff
  ON public.user_roles
  FOR SELECT
  TO authenticated
  USING (
    public.has_role((SELECT auth.uid()), 'admin'::public.app_role)
    OR public.has_role((SELECT auth.uid()), 'staff'::public.app_role)
  );

-- Do not expose profile/role data to anonymous clients or grant authenticated
-- clients role mutation privileges. Supabase service_role bypasses RLS and is
-- used only by server-side code.
REVOKE ALL ON TABLE public.profiles, public.user_roles FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.profiles, public.user_roles TO authenticated;
GRANT ALL ON TABLE public.profiles, public.user_roles TO service_role;

REVOKE USAGE ON TYPE public.app_role FROM PUBLIC, anon;
GRANT USAGE ON TYPE public.app_role TO authenticated, service_role;

-- Make newly created tables/functions visible to PostgREST without waiting for
-- its periodic schema-cache refresh.
NOTIFY pgrst, 'reload schema';

COMMIT;
